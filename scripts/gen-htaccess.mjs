/*
 * Builds dist/.htaccess for the cPanel (Apache) hosting, from the same vercel.json that
 * gen-redirects.mjs writes. Apache never reads vercel.json, so every rule the site relies on is
 * restated here: https + non-www, the legacy 301s (exact, by product id, /public prefix, .php),
 * clean URLs without a trailing slash, the 404 page, and the cache / security headers.
 *
 * Runs after the build (postbuild), because it writes into dist/.
 */
import fs from 'node:fs';

const HOST = 'runiindustries.eu';
const vercel = JSON.parse(fs.readFileSync('vercel.json', 'utf8'));

/* A literal path as a RewriteRule pattern: regex characters escaped, spaces kept (the pattern is
   quoted). Apache matches against the DECODED path, so "%20" and " " are the same rule. */
const literal = (p) => decodeURIComponent(p).replace(/^\//, '').replace(/[.+?^${}()|[\]\\*]/g, '\\$&');

const lines = [];
const seen = new Set();
const rule = (pattern, dest, flags = 'R=301,L') => {
  const key = pattern + '→' + dest;
  if (seen.has(key)) return;
  seen.add(key);
  lines.push(`RewriteRule "${pattern}" "${dest}" [${flags}]`);
};

lines.push(
  '# Generated by scripts/gen-htaccess.mjs from vercel.json. Do not edit by hand.',
  'Options -Indexes -MultiViews',
  'DirectorySlash Off',
  'DirectoryIndex index.html',
  'ErrorDocument 404 /404/index.html',
  '',
  'RewriteEngine On',
  'RewriteBase /',
  '',
  '# One host: https, no www.',
  'RewriteCond %{HTTPS} !=on [OR]',
  'RewriteCond %{HTTP_HOST} ^www\\. [NC]',
  `RewriteRule ^ https://${HOST}%{REQUEST_URI} [R=301,L]`,
  '',
  '# Legacy URLs from the old site, one hop each. Exact addresses first, then patterns.',
);

for (const r of vercel.redirects) {
  if (r.has) continue;                                   // the www rule above covers it
  const src = r.source;
  if (src === '/:path*.php' || src === '/public/:path*' || src === '/enquiry/:path*') continue;
  const m = src.match(/^\/(public\/)?product\/:s\/(\d+)$/);
  if (m) {
    if (m[1]) continue;                                  // the (public/)? prefix covers both
    rule(`^(?:public/)?product/[^/]+/${m[2]}/?$`, r.destination);
    continue;
  }
  rule(`^${literal(src)}/?$`, r.destination);
}

lines.push(
  '',
  '# Old enquiry links go to the quote form; the old /public prefix is dropped; .php is gone.',
  'RewriteRule "^enquiry(?:/.*)?$" "/contact?tab=rfq" [R=301,L]',
  'RewriteRule "^public/(.*)$" "/$1" [R=301,L]',
  'RewriteRule "^.*\\.php$" "/" [R=301,L,NC]',
  '',
  '# Clean URLs: no trailing slash on the canonical address, and /about serves /about/index.html.',
  'RewriteCond %{REQUEST_URI} ^(.+)/$',
  'RewriteRule "^(.+)/$" "/$1" [R=301,L]',
  'RewriteCond %{DOCUMENT_ROOT}/$1/index.html -f',
  'RewriteRule "^(.+)$" "/$1/index.html" [L]',
  '',
  '<IfModule mod_headers.c>',
);
for (const h of vercel.headers) {
  const path = h.source.replace(/^\//, '').replace(/\(\.\*\)/, '.*');
  lines.push(`  <If "%{REQUEST_URI} =~ m#^/${path}$#">`);
  for (const kv of h.headers) lines.push(`    Header set ${kv.key} "${kv.value}"`);
  lines.push('  </If>');
}
lines.push(
  '  <FilesMatch "\\.(html)$">',
  '    Header set Cache-Control "public, max-age=0, must-revalidate"',
  '  </FilesMatch>',
  '</IfModule>',
  '',
  '<IfModule mod_deflate.c>',
  '  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml',
  '</IfModule>',
  '',
);

fs.writeFileSync('dist/.htaccess', lines.join('\n'));
console.log(`.htaccess: ${lines.filter((l) => l.startsWith('RewriteRule')).length} rewrite rules`);
